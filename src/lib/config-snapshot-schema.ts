/** Keys to skip when spreading config_snapshot into config (preserve display values from CP/bom_preview). */
export const CONFIG_SNAPSHOT_SKIP_ON_SPREAD = new Set([
  ...CONFIG_SNAPSHOT_COST_KEYS,
  'productType',
  'product_type_id',
  'productTypeId',
  'quote_line_id',
  'configured_product_id',
]);

/**
 * Removes cost/total keys from an object before persisting as config_snapshot.
 * Call this whenever building config_snapshot for create_configured_product_and_bom_preview.
 */
export function stripCostKeys<T extends Record<string, unknown>>(obj: T): T {
  if (!obj || typeof obj !== 'object') return obj;
  const result = { ...obj } as Record<string, unknown>;
  for (const key of CONFIG_SNAPSHOT_COST_KEYS) {
    if (key in result) delete result[key];
  }
  return result as T;
}

/**
 * Returns a shallow copy of obj with only keys allowed in config_snapshot.
 * Use when building config_snapshot from a mixed config that may contain display/cost keys.
 */
export function configSnapshotOnly<T extends Record<string, unknown>>(obj: T): Record<string, unknown> {
  if (!obj || typeof obj !== 'object') return {};
  const result: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(obj)) {
    if (!CONFIG_SNAPSHOT_COST_KEYS.has(k) && v !== undefined && v !== null) {
      result[k] = v;
    }
  }
  return result;
}
