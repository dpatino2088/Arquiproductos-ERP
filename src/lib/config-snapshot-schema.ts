/**
 * Config Snapshot Schema Contract
 *
 * config_snapshot: SOLO configuración (dimensiones, selección de SKUs/ids, opciones).
 * NO debe contener costos ni totales (cost/total keys are stripped before save).
 *
 * bom_preview_snapshot: Generado por SQL (build_bom_preview_snapshot + calculate_configured_product_totals).
 * Fuente de verdad para totales: totals.roll_msrp_total, totals.bom_total, totals.total_msrp,
 * totals.roll_total_cost, totals.bom_total_cost, totals.unit_product_cost, totals.total_cost.
 *
 * Fuente de precios/costos de catálogo: CatalogItemsMSRP (msrp, pricing_cost_exw/total_cost).
 */

